-- Jornada PostgreSQL - persistência do Processor (Silver/Identidade/Gold/Serving).
--
-- Escopo desta fatia:
--   * observações cadastrais e factuais versionadas;
--   * identidade determinística por CPF e vínculo de observação;
--   * atributos transversais, conferência documental e referência territorial;
--   * materialização Gold/Serving de benefícios e serviços;
--   * QC factual e divergência de identidade.
--
-- Não declara paridade do subsistema analítico de Linkage (calibração/runner Fellegi-Sunter).
-- O Processor pode manter observações sem CPF como PENDENTE_IDENTIDADE até esse subsistema ser portado.

CREATE SCHEMA IF NOT EXISTS qualidade;

