CREATE TABLE IF NOT EXISTS silver.referencia_territorial_observacao(
    referencia_territorial_observacao_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pessoa_atributo_observacao_id BIGINT NOT NULL UNIQUE REFERENCES silver.pessoa_atributo_observacao(pessoa_atributo_observacao_id) ON DELETE CASCADE,
    natureza_referencia VARCHAR(50) NOT NULL CHECK(natureza_referencia IN ('DOMICILIAR','ACOLHIMENTO_INSTITUCIONAL','REFERENCIA_TERRITORIAL_DECLARADA')),
    fonte_semantica VARCHAR(30) NOT NULL CHECK(fonte_semantica IN ('REFERENCIA_TERRITORIAL','ENDERECO_RESIDENCIAL')),
    subprefeitura_id BIGINT NULL REFERENCES ref.subprefeitura(subprefeitura_id),
    distrito_id BIGINT NULL REFERENCES ref.distrito(distrito_id),
    situacao_geografia VARCHAR(40) NULL CHECK(situacao_geografia IS NULL OR situacao_geografia IN ('RESOLVIDA','FORA_MUNICIPIO','SEM_ENDERECO_APTO','NAO_RESOLVIDA_ORIGEM')),
    origem_geografia VARCHAR(30) NULL,
    referencia_malha VARCHAR(120) NULL,
    resolvido_em TIMESTAMPTZ NULL,
    CONSTRAINT ck_pg_referencia_domiciliar CHECK(fonte_semantica <> 'ENDERECO_RESIDENCIAL' OR natureza_referencia='DOMICILIAR'),
    CONSTRAINT ck_pg_referencia_geo_coerente CHECK(
        (situacao_geografia='RESOLVIDA' AND subprefeitura_id IS NOT NULL AND distrito_id IS NOT NULL AND referencia_malha IS NOT NULL AND resolvido_em IS NOT NULL)
        OR (situacao_geografia IS DISTINCT FROM 'RESOLVIDA' AND subprefeitura_id IS NULL AND distrito_id IS NULL AND origem_geografia IS NULL AND referencia_malha IS NULL AND resolvido_em IS NULL)
    )
);

CREATE OR REPLACE VIEW silver.v_pessoa_referencia_territorial AS
SELECT po.pessoa_observacao_id,
       x.referencia_territorial_observacao_id,
       x.pessoa_atributo_observacao_id,
       x.natureza_referencia,
       x.fonte_semantica,
       x.subprefeitura_id,
       x.distrito_id,
       x.situacao_geografia,
       x.origem_geografia,
       x.referencia_malha,
       x.resolvido_em
FROM silver.pessoa_observacao po
LEFT JOIN LATERAL (
    SELECT rt.referencia_territorial_observacao_id,
           pa.pessoa_atributo_observacao_id,
           rt.natureza_referencia,
           rt.fonte_semantica,
           rt.subprefeitura_id,
           rt.distrito_id,
           rt.situacao_geografia,
           rt.origem_geografia,
           rt.referencia_malha,
           rt.resolvido_em
      FROM silver.pessoa_atributo_observacao pa
      JOIN silver.referencia_territorial_observacao rt
        ON rt.pessoa_atributo_observacao_id=pa.pessoa_atributo_observacao_id
     WHERE pa.pessoa_observacao_id=po.pessoa_observacao_id
     ORDER BY CASE WHEN rt.fonte_semantica='REFERENCIA_TERRITORIAL' THEN 0 ELSE 1 END,
              CASE WHEN pa.status_evidencia='COMPROVADO' THEN 0 ELSE 1 END,
              COALESCE(pa.referencia_evidencia,pa.verificado_em,pa.atualizado_em_origem,pa.ingested_at) DESC,
              pa.pessoa_atributo_observacao_id DESC
     LIMIT 1
) x ON TRUE;

